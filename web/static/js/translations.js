/**
 * Detects initial language from localStorage or browser/system settings.
 * Defaults to system language if supported, otherwise 'en'.
 */
function detectSystemLanguage() {
  const saved = localStorage.getItem("gazebo_actors_lang");
  if (saved && SUPPORTED_LANGUAGES.includes(saved)) {
    return saved;
  }
  const browserLangs = navigator.languages || [navigator.language || navigator.userLanguage || "es"];
  for (const bl of browserLangs) {
    if (!bl) continue;
    const prefix = bl.toLowerCase().slice(0, 2);
    if (SUPPORTED_LANGUAGES.includes(prefix)) {
      return prefix;
    }
  }
  return "en";
}

let currentLanguage = detectSystemLanguage();

/**
 * Gets translation for key in current language with fallback to Spanish.
 */
function t(key, replacements = {}) {
  const dict = TRANSLATIONS[currentLanguage] || TRANSLATIONS.es;
  let text = dict[key] || TRANSLATIONS.es[key] || key;
  for (const [k, v] of Object.entries(replacements)) {
    text = text.replace(new RegExp(`\\{${k}\\}`, "g"), v);
  }
  return text;
}

/**
 * Applies language to all DOM elements with data-i18n, data-i18n-placeholder, data-i18n-title.
 */
function applyLanguage(lang) {
  if (!SUPPORTED_LANGUAGES.includes(lang)) lang = "es";
  currentLanguage = lang;
  localStorage.setItem("gazebo_actors_lang", lang);
  document.documentElement.lang = lang;

  // Update language selector in header if present
  const langSelect = document.getElementById("lang-select");
  if (langSelect && langSelect.value !== lang) {
    langSelect.value = lang;
  }

  // Translate text content
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (key) {
      el.textContent = t(key);
    }
  });

  // Translate placeholders
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (key) {
      el.placeholder = t(key);
    }
  });

  // Translate titles / tooltips
  document.querySelectorAll("[data-i18n-title]").forEach(el => {
    const key = el.getAttribute("data-i18n-title");
    if (key) {
      el.title = t(key);
    }
  });

  // Trigger dynamic update in app.js if loaded
  if (typeof onLanguageChanged === "function") {
    onLanguageChanged(lang);
  }
}
